import { API, API_GROUPS } from '../lua/docs';

/*
 * Справка по проверкам на Lua — для тех, кто будет менять код. Сначала — как всё устроено,
 * потом — полный список того, что есть в среде (тот же, что в подсказках у окна кода).
 */

const Code = ({ children }: { children: string }) => <pre className="help-code">{children}</pre>;

export function LuaHelp() {
  return (
    <div className="stack help">
      <section className="card stack">
        <h2>Как устроена проверка</h2>
        <p>
          Каждый столбец анкеты проверяет свой короткий код на <strong>Lua</strong> («Шаблоны и правила» → столбец → «Код проверки»).
          Код запускается для каждой ячейки отдельно: в <code>value</code> — её значение. Сначала выполняются{' '}
          <strong>общие проверки</strong> (одни для всех ячеек), потом — код столбца.
        </p>
        <p>
          Обычно код менять не нужно: у столбца есть <strong>настройки</strong> — переключатели, числа, списки. Их объявляет сам код
          через <code>setting.*</code>, и они появляются кнопками. Например, «Курс до» — это <code>setting.number("Курс до", 6)</code>.
        </p>
        <h3>Что код отдаёт</h3>
        <ul>
          <li>
            <code>problem("…")</code> — <strong>ошибка</strong> (красная): анкета не готова, пока не исправят или не проигнорируют.
          </li>
          <li>
            <code>warning("…")</code> — <strong>предупреждение</strong> (жёлтое): снимается галочкой «Проверено, значение верное».
          </li>
          <li>
            <code>notice("…")</code> — <strong>совет</strong> (серый): ни на что не влияет.
          </li>
          <li>
            <code>confirm()</code> — попросить галочку у каждого человека («индивидуальное значение»).
          </li>
          <li>
            <code>{'{ fix = … }'}</code> — исправленное значение: у ячейки появится кнопка «Применить», а у таблицы — «Исправить по
            шаблону».
          </li>
          <li>
            <code>unique()</code> — значение не должно повторяться у других людей (в таблице и в базе людей).
          </li>
        </ul>
        <h3>Пример целиком — «Курс»</h3>
        <Code>{`-- Пусто? Если «Обязательное» включено — ошибка. Дальше не проверяем.
if is_empty(true) then return end

-- Регулировки: появятся в настройках столбца
local from = setting.number("Курс от", 1)
local to = setting.number("Курс до", 6)

local n = lib.number(value)          -- текст → число
if not n or n < from or n > to then
  problem("Нужно число от " .. from .. " до " .. to)
end

if setting.toggle("Галочка у каждого человека", true) then
  confirm()
end`}</Code>
      </section>

      <section className="card stack">
        <h2>Другие ячейки и галочки</h2>
        <p>
          <code>cell("Группа")</code> — ячейка «Группа» этой же анкеты. У неё есть <code>.value</code> (значение), <code>.confirmed</code>{' '}
          (поставлена ли галочка «Проверено»), <code>.ok</code> (проверка без замечаний), <code>.status</code>, <code>.empty</code> и{' '}
          <code>.vars</code> — то, что код «Группы» запомнил через <code>remember</code>. Столбец можно назвать по-разному: «Группа»,
          номер 31 или id <code>edu.group</code>. Если такого столбца в таблице нет — <code>nil</code>, поэтому проверяйте: <code>if g then</code>.
        </p>
        <Code>{`-- В «Курсе»: сначала пусть проверят группу
local g = cell("Группа")
if g and not g.confirmed then
  warning("Сначала проверьте группу «" .. g.value .. "»")
end

-- В «Группе»: запомнить курс из названия «ИС-21» → «2»
remember("курс", lib.sub(value, 4, 4))
-- …а в «Курсе» прочитать
if g and g.vars["курс"] ~= value then
  problem("Курс не совпадает с группой")
end`}</Code>
        <p className="small muted">
          <code>confirmed</code> (без cell) — галочка у самой проверяемой ячейки. Галочка относится к значению: если значение изменят,
          она снимается.
        </p>
      </section>

      <section className="card stack">
        <h2>База данных</h2>
        <p>
          База — набор <strong>древ «ключ:значение»</strong>. Каждое древо — отдельный файл в рабочей папке:{' '}
          <code>.docassist/base/&lt;имя древа&gt;.json</code>. Сначала база пустая; значения попадают в неё, когда вы их подтверждаете в
          анкете («Верно — добавить в базу», «Новые слова») или добавляете вручную на вкладке «База».
        </p>
        <h3>Проверить по базе</h3>
        <ul>
          <li>
            <code>base.check()</code> — значение должно быть в базе. Древо — по названию столбца. Нет в базе — предупреждение «Нет в
            базе» и кнопка «Верно — добавить в базу».
          </li>
          <li>
            <code>{'base.check({ inside = "Код подразделения" })'}</code> — хранить внутри значения другого столбца: для кода 000-000
            верно только то, что подтверждено именно для него.
          </li>
          <li>
            <code>{'base.check({ tree = "Учебные заведения" })'}</code> — взять другое древо (например, общее для двух столбцов).
          </li>
          <li>
            <code>base.check_parts()</code> — для адресов и места рождения: ячейка дробится на части по <strong>конструктору</strong>{' '}
            (в настройках столбца), каждая часть сверяется с древом внутри предыдущей: «Примерск» внутри «Респ. Регион». Порядок
            уровней — «2, 1, 3, *».
          </li>
        </ul>
        <h3>Взять из базы</h3>
        <Code>{`base.has("Адреса", "Регион", value)   -- есть ли value внутри «Регион»
base.list("Должность в СО")           -- все значения верхнего уровня
base.list("Адреса", "Регион")         -- что лежит внутри «Регион»
base.find("Адреса", value)            -- где встречается: список путей
base.trees()                          -- названия всех древ

-- Пример: предупредить, если должности нет среди трёх первых
local all = base.list("Должность в СО")
if #all > 0 and not lib.one_of(value, all) then
  warning("Такой должности ещё нет в базе")
end`}</Code>
        <p className="small muted">
          Всё, что вы добавляете в базу, попадает и в «Предложения в базу» — их можно отправить разработчику, чтобы они вошли в общую
          базу.
        </p>
      </section>

      <section className="card stack">
        <h2>Своя библиотека и ошибки в коде</h2>
        <p>
          В «Моя библиотека» можно написать свои функции — их увидят все проверки. Функция, которая принимает текст и возвращает
          true/false, появится в конструкторе ячейки как проверка части.
        </p>
        <Code>{`function is_group(s)
  return lib.mask(s, "99-99") or lib.contains(s, "-")
end`}</Code>
        <p>
          Если в коде ошибка, в окне кода подсвечивается строка и пишется по-русски, что не так («не хватает end», «нет такой
          функции»). В анкете у ячейки появится «Ошибка в коде проверки» — её нельзя проигнорировать, только исправить. Бесконечный
          цикл обрывается сам. Чтобы посмотреть промежуточное значение, напишите <code>print(…)</code> — вывод видно в «Проверить
          значение».
        </p>
        <p className="small muted">
          Код работает только внутри DocAssist: без доступа к файлам и сети. Названия функций — латиницей (так устроен Lua), а
          тексты, названия столбцов и регулировок — по-русски, в кавычках.
        </p>
      </section>

      {API_GROUPS.map((g) => (
        <section key={g.id} className="card stack">
          <h2>{g.title}</h2>
          <p className="muted small" style={{ margin: 0 }}>
            {g.about}
          </p>
          <dl className="help-api">
            {API.filter((e) => e.group === g.id).map((e) => (
              <div key={e.name} className="help-api__item">
                <dt className="mono">{e.signature}</dt>
                <dd>
                  {e.about}
                  {e.example && <Code>{e.example}</Code>}
                </dd>
              </div>
            ))}
          </dl>
        </section>
      ))}
    </div>
  );
}
