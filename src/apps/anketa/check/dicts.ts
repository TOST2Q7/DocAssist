/** Уровень образования по коду направления. */
export function specialtyLevel(code: string): { title: string; maxCourse: number } | null {
  switch (code.slice(3, 5)) {
    case '02':
      return { title: 'СПО', maxCourse: 5 };
    case '03':
      return { title: 'бакалавриат', maxCourse: 5 };
    case '04':
      return { title: 'магистратура', maxCourse: 3 };
    case '05':
      return { title: 'специалитет', maxCourse: 6 };
    default:
      return null;
  }
}

/** Ключ для сравнения названий: без регистра, кавычек, знаков и лишних пробелов. */
export function looseKey(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/["«»“”„'.,;:()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
