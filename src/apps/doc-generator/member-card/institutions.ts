/** Для сравнения: без регистра, «ё», вида кавычек, тире и лишних пробелов. */
const norm = (s: string) =>
  s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/["„“”«»]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/\s+/g, ' ')
    .trim();

/** Сокращённое название по методичке, если записано полное (или сокращённое с другими кавычками). */
export function shortInstitution(value: string): string | undefined {
  const v = norm(value);
  if (!v) return undefined;
  const found = INSTITUTIONS.find((i) => norm(i.full) === v || norm(i.short) === v);
  return found && found.short !== value.trim() ? found.short : undefined;
}
