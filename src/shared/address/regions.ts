/** Республики с названием-прилагательным пишутся «Удмуртская Респ.», остальные — «Респ. Хакасия». */
const ADJECTIVE_REPUBLICS = new Set(['Кабардино-Балкарская', 'Карачаево-Черкесская', 'Удмуртская', 'Чеченская', 'Чувашская', 'Донецкая Народная', 'Луганская Народная']);

function forms(name: string, type: RegionType): { short: string; full: string } {
  switch (type) {
    case 'resp':
      return ADJECTIVE_REPUBLICS.has(name)
        ? { short: `${name} Респ.`, full: `${name} Республика` }
        : { short: `Респ. ${name}`, full: `Республика ${name}` };
    case 'kray':
      return { short: `${name} край`, full: `${name} край` };
    case 'obl':
      return { short: `${name} обл.`, full: `${name} область` };
    case 'gfz':
      return { short: `г. ${name}`, full: `город ${name}` };
    case 'ao':
      return { short: `${name} АО`, full: `${name} автономный округ` };
    case 'aobl':
      return { short: `${name} Аобл.`, full: `${name} автономная область` };
  }
}

export const REGIONS: Region[] = ROWS.map(([subject, okato, name, type, aliases, extra]) => ({
  subject,
  okato,
  name,
  type,
  ...forms(name, type),
  aliases,
  ...extra,
}));

export function regionBySubject(code: string): Region | undefined {
  return REGIONS.find((r) => r.subject === code);
}

export function regionsByOkato(code: string): Region[] {
  return REGIONS.filter((r) => r.okato === code);
}
